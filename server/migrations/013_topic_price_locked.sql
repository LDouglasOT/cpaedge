ALTER TABLE topics ADD COLUMN IF NOT EXISTS price INTEGER NOT NULL DEFAULT 0;
ALTER TABLE topics ADD COLUMN IF NOT EXISTS locked BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS topic_purchases (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  topic_id TEXT NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  purchased_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  UNIQUE (student_id, topic_id)
);
